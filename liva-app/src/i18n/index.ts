export function t(key: string, vars?: Record<string, string | number>): string {
  let s = DICT[state.lang]?.[key] ?? DICT.en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}

function fmtNum(n: number, dec: number) {
  return Number(n).toLocaleString('en-US', { minimumFractionDigits: dec, maximumFractionDigits: dec });
}

// USD → formatted string in active currency
export function price(usd: number, opts: { dec?: number } = {}): string {
  if (state.ccy === 'AED') {
    const v = usd * AED_RATE;
    const num = fmtNum(v, opts.dec ?? 0);
    return state.lang === 'ar' ? `${num} د.إ` : `AED ${num}`;
  }
  return '$' + fmtNum(usd, opts.dec ?? 2);
}

export function fmtK(n: number): string {
  if (n >= 1000) return (n / 1000).toFixed(n % 1000 === 0 ? 0 : 1) + 'K';
  return String(n);
}

// pick product name honoring language
export function pname<T extends { name: string; nameAr?: string }>(p: T): string {
  return state.lang === 'ar' && p.nameAr ? p.nameAr : p.name;
}
